"""Narrative catalog for 100 riverside drift items.

All descriptions are intentionally compact and fit a single inspection page
under the RIV010 layout.  Placement is not stored here; the stage owns world
coordinates and interaction bounds.

The catalog deliberately avoids directly stating what happened to humanity.
Later-area items carry stronger traces of the cat's former owner and of the
collapsed water-magic city upstream.
"""

from __future__ import annotations

from dataclasses import dataclass
from enum import Enum
from typing import Final, TypeVar


class DriftCategory(str, Enum):
    HOUSEHOLD = "household"
    CAT_HOME = "cat_home"
    CITY = "city"
    MAGIC_MACHINE = "magic_machine"
    NATURALIZED = "naturalized"
    ANOMALY = "anomaly"
    OWNER_TRACE = "owner_trace"


class DriftRarity(str, Enum):
    COMMON = "common"
    UNCOMMON = "uncommon"
    RARE = "rare"
    ECHO = "echo"


@dataclass(frozen=True, slots=True)
class DriftItemDefinition:
    item_id: str
    title: str
    body: str
    category: DriftCategory
    rarity: DriftRarity

    # Relative probability among currently eligible items.
    spawn_weight: int

    # A..R is represented as 0..17.  A later item is never selected before
    # this area unless the caller explicitly bypasses progression filtering.
    min_area_index: int

    # Key memories, anomalies and owner traces should not repeat in one save.
    unique_per_save: bool
    owner_handwriting: bool

    # 0: ambience, 1: city/magic hint, 2: personal trace, 3: direct story clue.
    clue_level: int

    # Suggested billboard and interaction tuning values.
    world_width: float
    marker_offset_y: float
    acquire_padding_x: float
    acquire_padding_z: float

    @property
    def text_key(self) -> str:
        return self.item_id

    @property
    def sprite_id(self) -> str:
        return self.item_id


