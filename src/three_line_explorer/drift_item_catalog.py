DRIFT_ITEM_IDS: Final[tuple[str, ...]] = tuple(
    item.item_id for item in DRIFT_ITEMS
)

DRIFT_ITEM_BY_ID: Final[dict[str, DriftItemDefinition]] = {
    item.item_id: item for item in DRIFT_ITEMS
}


def get_drift_item(item_id: str) -> DriftItemDefinition:
    try:
        return DRIFT_ITEM_BY_ID[item_id]
    except KeyError as exc:
        raise KeyError(f"Unknown drift item id: {item_id}") from exc


InspectionTextT = TypeVar("InspectionTextT")


def instantiate_inspection_texts(
    inspection_text_type: type[InspectionTextT],
) -> dict[str, InspectionTextT]:
    """Adapt this catalog to riverside's existing InspectionText class."""

    return {
        item.text_key: inspection_text_type(
            title=item.title,
            pages=(item.body,),
        )
        for item in DRIFT_ITEMS
    }


def validate_catalog() -> None:
    if len(DRIFT_ITEMS) != 100:
        raise ValueError(
            f"Expected exactly 100 drift items, got {len(DRIFT_ITEMS)}"
        )

    if len(DRIFT_ITEM_BY_ID) != len(DRIFT_ITEMS):
        raise ValueError("Duplicate drift item_id detected")

    titles = [item.title for item in DRIFT_ITEMS]
    if len(set(titles)) != len(titles):
        raise ValueError("Duplicate drift item title detected")

    for item in DRIFT_ITEMS:
        if not item.item_id:
            raise ValueError("Empty drift item_id")
        if not item.title.strip():
            raise ValueError(f"{item.item_id}: empty title")
        if not item.body.strip():
            raise ValueError(f"{item.item_id}: empty body")
        if "\n" in item.body or "\r" in item.body:
            raise ValueError(
                f"{item.item_id}: body must be one logical paragraph"
            )
        if len(item.body) > 60:
            raise ValueError(
                f"{item.item_id}: body is too long ({len(item.body)} chars)"
            )
        if item.spawn_weight <= 0:
            raise ValueError(f"{item.item_id}: invalid spawn_weight")
        if not 0 <= item.min_area_index <= 17:
            raise ValueError(f"{item.item_id}: invalid min_area_index")
        if not 0 <= item.clue_level <= 3:
            raise ValueError(f"{item.item_id}: invalid clue_level")
        if item.world_width <= 0.0:
            raise ValueError(f"{item.item_id}: invalid world_width")


validate_catalog()
