def allowed_source_chars(
    transparent_color: int | None,
) -> frozenset[str]:
    if transparent_color is None:
        return frozenset(HEX_DIGITS)

    if not 0 <= transparent_color <= 15:
        raise ValueError(
            f"transparent_color must be 0..15 or None: {transparent_color}"
        )

    reserved = f"{transparent_color:x}"
    return frozenset("." + HEX_DIGITS.replace(reserved, ""))


def validate_pixel_map(spec: PixelMapSpec) -> None:
    if spec.width <= 0 or spec.height <= 0:
        raise ValueError(f"{spec.asset_id}: dimensions must be positive")

    if len(spec.rows) != spec.height:
        raise ValueError(
            f"{spec.asset_id}: expected {spec.height} rows, "
            f"got {len(spec.rows)}"
        )

    allowed = allowed_source_chars(spec.transparent_color)
    visible_pixels = 0

    for y, row in enumerate(spec.rows):
        if len(row) != spec.width:
            raise ValueError(
                f"{spec.asset_id}: row {y} must be {spec.width} chars, "
                f"got {len(row)}"
            )

        invalid = set(row) - allowed
        if invalid:
            raise ValueError(
                f"{spec.asset_id}: invalid chars on row {y}: "
                f"{sorted(invalid)}"
            )

        visible_pixels += sum(char != "." for char in row)

    if visible_pixels == 0:
        raise ValueError(f"{spec.asset_id}: map is fully transparent")


def validate_all_assets() -> None:
    asset_ids: set[str] = set()

    for tile in PARALLAX_TILES.values():
        validate_pixel_map(tile.source)
        if tile.source.asset_id in asset_ids:
            raise ValueError(f"duplicate asset id: {tile.source.asset_id}")
        asset_ids.add(tile.source.asset_id)

    for sprite in WORLD_SPRITES.values():
        validate_pixel_map(sprite.source)
        if sprite.source.asset_id in asset_ids:
            raise ValueError(f"duplicate asset id: {sprite.source.asset_id}")
        asset_ids.add(sprite.source.asset_id)

        if not 0 <= sprite.anchor_x < sprite.source.width:
            raise ValueError(f"{sprite.source.asset_id}: anchor_x out of bounds")
        if not 0 <= sprite.anchor_y < sprite.source.height:
            raise ValueError(f"{sprite.source.asset_id}: anchor_y out of bounds")
        if sprite.world_width <= 0:
            raise ValueError(
                f"{sprite.source.asset_id}: world_width must be positive"
            )

        collidable = sprite.kind in {
            WorldSpriteKind.SOLID,
            WorldSpriteKind.SOLID_INSPECTABLE,
        }
        if collidable:
            if sprite.collision_half_x <= 0 or sprite.collision_half_z <= 0:
                raise ValueError(
                    f"{sprite.source.asset_id}: solid sprite needs a "
                    "positive collision footprint"
                )
        elif sprite.collision_half_x != 0 or sprite.collision_half_z != 0:
            raise ValueError(
                f"{sprite.source.asset_id}: non-solid sprite must have a "
                "zero collision footprint"
            )

    for layer, sequence in PARALLAX_SEQUENCES.items():
        if len(sequence) != 4:
            raise ValueError(
                f"{layer.value}: expected four tiles, got {len(sequence)}"
            )


def compile_rows(spec: PixelMapSpec) -> list[str]:
    validate_pixel_map(spec)
    if spec.transparent_color is None:
        return list(spec.rows)

    transparent_digit = f"{spec.transparent_color:x}"
    return [row.replace(".", transparent_digit) for row in spec.rows]


