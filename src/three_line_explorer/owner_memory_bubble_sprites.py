@dataclass(frozen=True, slots=True)
class OwnerMemoryBubbleAtlas:
    image: Any


def validate_owner_memory_frames() -> None:
    if len(OWNER_MEMORY_FRAMES) != FRAME_COUNT:
        raise ValueError(
            f"expected {FRAME_COUNT} frames, got {len(OWNER_MEMORY_FRAMES)}"
        )

    for frame_index, rows in enumerate(OWNER_MEMORY_FRAMES):
        if len(rows) != FRAME_H:
            raise ValueError(
                f"frame {frame_index}: expected {FRAME_H} rows, "
                f"got {len(rows)}"
            )

        visible_pixels = 0

        for row_index, row in enumerate(rows):
            if len(row) != FRAME_W:
                raise ValueError(
                    f"frame {frame_index}, row {row_index}: "
                    f"expected width {FRAME_W}, got {len(row)}"
                )

            invalid = set(row) - _ALLOWED_CHARS

            if invalid:
                raise ValueError(
                    f"frame {frame_index}, row {row_index}: "
                    f"invalid chars {sorted(invalid)}"
                )

            visible_pixels += sum(char != "." for char in row)

        if visible_pixels == 0:
            raise ValueError(f"frame {frame_index} is fully transparent")


def compile_rows(rows: tuple[str, ...]) -> list[str]:
    return [
        row.replace(".", TRANSPARENT_DIGIT)
        for row in rows
    ]


def instantiate_pixel_map_sources(
    pixel_map_source_type: type[Any],
) -> dict[str, Any]:
    """Adapt the frames to riverside's PixelMapSource contract."""

    validate_owner_memory_frames()

    return {
        f"owner_memory_bubble_{frame_index}": pixel_map_source_type(
            width=FRAME_W,
            height=FRAME_H,
            rows=rows,
            transparent_color=TRANSPARENT_COLOR,
        )
        for frame_index, rows in enumerate(OWNER_MEMORY_FRAMES)
    }


def build_owner_memory_bubble_atlas(pyxel: Any | None = None) -> OwnerMemoryBubbleAtlas:
    """Build one 256x64 Pyxel Image after pyxel.init()."""

    if pyxel is None:
        import pyxel as pyxel_module

        pyxel = pyxel_module

    validate_owner_memory_frames()

    image = pyxel.Image(ATLAS_W, ATLAS_H)
    image.cls(TRANSPARENT_COLOR)

    for frame_index, rows in enumerate(OWNER_MEMORY_FRAMES):
        image.set(
            frame_index * FRAME_W,
            0,
            compile_rows(rows),
        )

    return OwnerMemoryBubbleAtlas(image=image)


def animation_frame_index(
    elapsed_frames: int,
    *,
    frame_hold: int = DEFAULT_FRAME_HOLD,
) -> int:
    """Return the frame for a panel-local elapsed-frame counter."""

    if elapsed_frames < 0:
        raise ValueError("elapsed_frames must be non-negative")

    if frame_hold <= 0:
        raise ValueError("frame_hold must be positive")

    sequence_index = (
        elapsed_frames // frame_hold
    ) % len(ANIMATION_SEQUENCE)

    return ANIMATION_SEQUENCE[sequence_index]


def draw_owner_memory_bubble(
    atlas: OwnerMemoryBubbleAtlas,
    *,
    frame_index: int,
    cat_head_screen_x: float,
    cat_head_screen_y: float,
) -> None:
    """Draw the cloud with its smallest puff attached to the cat's head.

    The caller should draw this after world sprites and before the
    inspection panel. The sprite is intentionally fixed at 1x scale.
    """

    import pyxel

    if not 0 <= frame_index < FRAME_COUNT:
        raise ValueError(f"invalid frame_index: {frame_index}")

    draw_x = round(cat_head_screen_x - ANCHOR_X)
    draw_y = round(cat_head_screen_y - ANCHOR_Y)

    pyxel.blt(
        draw_x,
        draw_y,
        atlas.image,
        frame_index * FRAME_W,
        0,
        FRAME_W,
        FRAME_H,
        TRANSPARENT_COLOR,
    )


