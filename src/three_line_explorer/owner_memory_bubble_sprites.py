"""Four-frame owner recollection bubble for riverside.

The art is source-defined using Pyxel color indexes. A dot is an
authoring shorthand for transparency and is converted to color index 2
when the runtime atlas is built.

Frame design:
    0: memory appears; small, gentle smile
    1: eyes narrow and cheeks soften
    2: closed-eye smile; cloud rises
    3: fullest smile; cloud settles

Recommended loop:
    0, 1, 2, 3, 2, 1
"""

