def validate_sprite_rows(
    sprite_id: str,
    rows: tuple[str, ...],
) -> None:
    if len(rows) != CELL_H:
        raise ValueError(
            f"{sprite_id}: expected {CELL_H} rows, got {len(rows)}"
        )

    visible_count = 0

    for y, row in enumerate(rows):
        if len(row) != CELL_W:
            raise ValueError(
                f"{sprite_id}: row {y} must have {CELL_W} chars, "
                f"got {len(row)}"
            )

        invalid = set(row) - _VALID_SOURCE_CHARS
        if invalid:
            raise ValueError(
                f"{sprite_id}: invalid chars at row {y}: {sorted(invalid)}"
            )

        if TRANSPARENT_DIGIT in row:
            raise ValueError(
                f"{sprite_id}: visible color {TRANSPARENT_DIGIT} conflicts "
                "with this asset's transparent color"
            )

        visible_count += sum(char != "." for char in row)

    if visible_count == 0:
        raise ValueError(f"{sprite_id}: fully transparent sprite")


def validate_all_sprites() -> None:
    catalog_ids = set(DRIFT_ITEM_IDS)
    sprite_ids = set(SPRITE_ROWS)

    if sprite_ids != catalog_ids:
        missing = sorted(catalog_ids - sprite_ids)
        extra = sorted(sprite_ids - catalog_ids)
        raise ValueError(
            f"Catalog/sprite mismatch. missing={missing}, extra={extra}"
        )

    seen_maps: set[tuple[str, ...]] = set()

    for sprite_id in DRIFT_ITEM_IDS:
        rows = SPRITE_ROWS[sprite_id]
        validate_sprite_rows(sprite_id, rows)

        if rows in seen_maps:
            raise ValueError(f"{sprite_id}: duplicate sprite map")
        seen_maps.add(rows)


def _compile_rows(rows: tuple[str, ...]) -> list[str]:
    return [
        row.replace(".", TRANSPARENT_DIGIT)
        for row in rows
    ]


def _visible_bounds(
    rows: tuple[str, ...],
) -> tuple[int, int, int, int]:
    points = [
        (x, y)
        for y, row in enumerate(rows)
        for x, char in enumerate(row)
        if char != "."
    ]

    if not points:
        raise ValueError("Cannot find bounds of transparent sprite")

    xs = [x for x, _ in points]
    ys = [y for _, y in points]
    return min(xs), min(ys), max(xs), max(ys)


PixelMapSourceT = TypeVar("PixelMapSourceT")


def instantiate_pixel_map_sources(
    pixel_map_source_type: type[PixelMapSourceT],
) -> dict[str, PixelMapSourceT]:
    """Adapt the maps to the PixelMapSource contract accepted by Codex."""

    return {
        sprite_id: pixel_map_source_type(
            width=CELL_W,
            height=CELL_H,
            rows=rows,
            transparent_color=TRANSPARENT_COLOR,
        )
        for sprite_id, rows in SPRITE_ROWS.items()
    }


def build_drift_sprite_atlas(pyxel: Any | None = None) -> DriftSpriteAtlas:
    """Build two 256x256 runtime atlas pages once after pyxel.init()."""

    if pyxel is None:
        import pyxel as pyxel_module

        pyxel = pyxel_module

    validate_all_sprites()

    images = tuple(
        pyxel.Image(ATLAS_PAGE_W, ATLAS_PAGE_H)
        for _ in range(ATLAS_PAGE_COUNT)
    )

    for image in images:
        image.cls(TRANSPARENT_COLOR)

    regions: dict[str, DriftSpriteRegion] = {}

    for index, sprite_id in enumerate(DRIFT_ITEM_IDS):
        page_index = index // ATLAS_CAPACITY
        local_index = index % ATLAS_CAPACITY
        column = local_index % ATLAS_COLUMNS
        row = local_index // ATLAS_COLUMNS
        u = column * CELL_W
        v = row * CELL_H
        rows = SPRITE_ROWS[sprite_id]

        images[page_index].set(
            u,
            v,
            _compile_rows(rows),
        )

        min_x, _min_y, max_x, max_y = _visible_bounds(rows)
        item = DRIFT_ITEM_BY_ID[sprite_id]

        regions[sprite_id] = DriftSpriteRegion(
            page_index=page_index,
            u=u,
            v=v,
            width=CELL_W,
            height=CELL_H,
            anchor_x=(min_x + max_x) // 2,
            anchor_y=max_y,
            world_width=item.world_width,
            marker_offset_y=item.marker_offset_y,
        )

    return DriftSpriteAtlas(
        images=images,
        regions=regions,
    )


def draw_drift_sprite_1x(
    atlas: DriftSpriteAtlas,
    sprite_id: str,
    screen_x: float,
    screen_ground_y: float,
) -> None:
    """Draw with the visible bottom-center aligned to a projected anchor."""

    import pyxel

    region = atlas.regions[sprite_id]
    image = atlas.images[region.page_index]

    pyxel.blt(
        round(screen_x - region.anchor_x),
        round(screen_ground_y - region.anchor_y),
        image,
        region.u,
        region.v,
        region.width,
        region.height,
        TRANSPARENT_COLOR,
    )


